export function isRTL(lang: AppLanguage): boolean {
  return lang === 'he';
}

export function detectContentLanguage(text: string): AppLanguage {
  if (!text) return 'en';
  // Check for Hebrew characters
  const hebrewRegex = /[\u0590-\u05FF]/;
  return hebrewRegex.test(text) ? 'he' : 'en';
}
